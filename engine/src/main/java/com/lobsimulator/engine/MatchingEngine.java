package com.lobsimulator.engine;

import java.util.ArrayList;
import java.util.List;
import java.io.IOException;

/**
 * Single-threaded deterministic matching engine.
 * Supports LIMIT, MARKET, IOC, and FOK order types.
 * Tracks fees, slippage, and VWAP per execution.
 */
public class MatchingEngine {
    private final OrderBook orderBook;
    private final FeeModel feeModel;
    private final TradeEventPool tradePool = new TradeEventPool(1000, 10000);
    private BinaryEventLogger logger;

    public MatchingEngine(OrderBook orderBook) {
        this(orderBook, new FeeModel());
    }

    public MatchingEngine(OrderBook orderBook, FeeModel feeModel) {
        this.orderBook = orderBook;
        this.feeModel = feeModel;
        try {
            this.logger = new BinaryEventLogger("trades.bin");
        } catch (IOException e) {
            // Non-fatal: log to stderr and continue without binary logging
            System.err.println("Warning: could not open trades.bin for logging: " + e.getMessage());
        }
    }

    public MatchingEngine() {
        this(new OrderBook());
    }

    /**
     * Processes an incoming order against the book.
     * Returns a list of TradeEvents generated by fills.
     */
    public List<TradeEvent> processOrder(Order order) {
        List<TradeEvent> trades = new ArrayList<>();
        if (order == null) return trades;

        boolean buySide = order.isBuySide();
        long price = order.getPrice();
        int remainingQty = order.getQuantity();
        long timestamp = order.getTimestamp();
        OrderType type = order.getType();

        // Capture mid-price before execution for slippage calculation
        long[] bestBid = orderBook.getBestBid();
        long[] bestAsk = orderBook.getBestAsk();
        double midPrice = (bestBid != null && bestAsk != null)
                ? (bestBid[0] + bestAsk[0]) / 2.0
                : price;

        // FOK: check full liquidity available before touching the book
        if (type == OrderType.FOK
                && orderBook.getTotalQuantityAtOrBetter(buySide, price) < remainingQty) {
            return trades;
        }

        String takerOrderId = order.getOrderId();
        double totalNotional = 0;
        int totalTradedQty = 0;

        outer:
        while (remainingQty > 0) {
            long bestOppositePrice;
            int oppositeQty;

            if (buySide) {
                long[] ba = orderBook.getBestAsk();
                if (ba == null) break;
                bestOppositePrice = ba[0];
                oppositeQty = (int) ba[1];
                if (type == OrderType.LIMIT && price < bestOppositePrice) break;
            } else {
                long[] bb = orderBook.getBestBid();
                if (bb == null) break;
                bestOppositePrice = bb[0];
                oppositeQty = (int) bb[1];
                if (type == OrderType.LIMIT && price > bestOppositePrice) break;
            }

            int qtyToTrade = Math.min(remainingQty, oppositeQty);
            int tradedAtLevel = 0;

            while (tradedAtLevel < qtyToTrade) {
                // buySide=false here because we want resting orders on the OPPOSITE side
                Order resting = orderBook.getFirstOrder(!buySide, bestOppositePrice);
                if (resting == null) break;

                int tQty = Math.min(resting.getQuantity(), qtyToTrade - tradedAtLevel);

                TradeEvent trade = tradePool.borrow(
                        bestOppositePrice, tQty, buySide,
                        resting.getOrderId(), takerOrderId, timestamp);

                // Slippage = distance from mid-price as a fraction
                double slippage = midPrice > 0
                        ? Math.abs(bestOppositePrice - midPrice) / midPrice
                        : 0.0;
                trade.setSlippage(slippage);

                totalNotional += (double) bestOppositePrice * tQty;
                totalTradedQty += tQty;
                trade.setVwap(totalTradedQty > 0 ? totalNotional / totalTradedQty : 0);

                long mFee = feeModel.calculateMakerFee(bestOppositePrice, tQty);
                long tFee = feeModel.calculateTakerFee(bestOppositePrice, tQty);
                trade.setMakerFee(mFee);
                trade.setTakerFee(tFee);

                // Credit/debit fees on the respective orders
                orderBook.updateOrderFees(resting.getOrderId(), -mFee, 0);
                order.addTakerFeePaid(tFee);

                trades.add(trade);
                feeModel.addVolume(bestOppositePrice, tQty);

                if (logger != null) {
                    try {
                        logger.logTrade(trade);
                    } catch (IOException e) {
                        System.err.println("Warning: failed to log trade: " + e.getMessage());
                    }
                }

                orderBook.reduceOrder(resting.getOrderId(), tQty);
                tradedAtLevel += tQty;
                remainingQty -= tQty;
                if (remainingQty == 0) break outer;
            }
        }

        // Post IOC: cancel any unfilled remainder
        // Post LIMIT: rest unfilled remainder in the book
        if (remainingQty > 0 && type == OrderType.LIMIT) {
            order.setQuantity(remainingQty);
            orderBook.addOrder(order);
        }
        // IOC and FOK remainders are simply discarded

        return trades;
    }

    public OrderBook getOrderBook() {
        return orderBook;
    }

    public FeeModel getFeeModel() {
        return feeModel;
    }

    public void shutdown() {
        if (logger != null) {
            try {
                logger.close();
            } catch (IOException e) {
                System.err.println("Warning: failed to close trade logger: " + e.getMessage());
            }
        }
    }
}
